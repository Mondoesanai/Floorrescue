// Generates src/app/concrete.css — the concrete surface theme. Everything is scoped to
// body.theme-concrete, so removing that class from <body> in layout.tsx restores the old look.
import fs from "node:fs";

const svg = (w, h, filter) =>
  `url("data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns='http://www.w3.org/2000/svg' width='${w}' height='${h}'><filter id='f' x='0' y='0' width='100%' height='100%'>${filter}</filter><rect width='100%' height='100%' filter='url(#f)'/></svg>`,
  )}")`;

const turb = (freq, oct, seed) => `<feTurbulence type='fractalNoise' baseFrequency='${freq}' numOctaves='${oct}' seed='${seed}' stitchTiles='stitch'/>`;
// colour + alpha derived from the red channel of the noise
const alphaFromR = (r, g, b, k, off) => `<feColorMatrix type='matrix' values='0 0 0 0 ${r}  0 0 0 0 ${g}  0 0 0 0 ${b}  ${k} 0 0 0 ${off}'/>`;

const tiles = {
  fineLight: svg(300, 300, turb(0.9, 3, 4) + alphaFromR(0.86, 0.86, 0.84, 1.1, -0.47)),
  fineFaint: svg(300, 300, turb(0.9, 3, 9) + alphaFromR(0.8, 0.8, 0.78, 0.55, -0.22)),
  pores: svg(380, 380, turb(0.42, 1, 21) + alphaFromR(0, 0, 0, 16, -12.6)),
  mottleLight: svg(1100, 1100, turb("0.004 0.006", 3, 5) + alphaFromR(0.72, 0.72, 0.7, 0.3, -0.1)),
  mottleDark: svg(1400, 1400, turb("0.0035 0.005", 3, 11) + alphaFromR(0, 0, 0, -0.4, 0.24)),
};

const css = `/* GENERATED by scripts/gen-concrete.mjs — concrete surface theme (see the CONCRETE_THEME flag in layout.tsx). */
body.theme-concrete {
  --cn-fine: ${tiles.fineLight};
  --cn-fine-faint: ${tiles.fineFaint};
  --cn-pores: ${tiles.pores};
  --cn-mottle-l: ${tiles.mottleLight};
  --cn-mottle-d: ${tiles.mottleDark};
  background-color: #414244;
  background-image: var(--cn-pores), var(--cn-fine), var(--cn-mottle-l), var(--cn-mottle-d),
    linear-gradient(180deg, rgba(255, 255, 255, 0.05), rgba(0, 0, 0, 0.16));
  background-size: 380px 380px, 300px 300px, 1100px 1100px, 1400px 1400px, 100% 100%;
}

/* Sections that were flat black become recessed channels cut into the slab. */
body.theme-concrete :is(section, footer)[class~="bg-charcoal-900"],
body.theme-concrete :is(section, footer)[class~="bg-charcoal-950"] {
  background-color: #17181a;
  background-image: var(--cn-pores), var(--cn-fine-faint), var(--cn-mottle-l);
  background-size: 380px 380px, 300px 300px, 1100px 1100px;
  box-shadow:
    inset 0 16px 26px -14px rgba(0, 0, 0, 0.95),
    inset 0 -12px 22px -14px rgba(0, 0, 0, 0.7),
    inset 0 1px 0 rgba(0, 0, 0, 0.9),
    inset 0 -1px 0 rgba(255, 255, 255, 0.08);
  border-top-color: transparent;
}

/* Cards, panels and wells: pockets pressed into the surface. */
body.theme-concrete :is(div, article, aside, li, blockquote, details, form)[class~="bg-charcoal-900"][class*="rounded"],
body.theme-concrete :is(div, article, aside, li, blockquote, details, form)[class~="bg-charcoal-950"][class*="rounded"],
body.theme-concrete :is(a, button)[class~="bg-charcoal-900"][class*="rounded"]:not([class*="fixed"]),
body.theme-concrete :is(a, button)[class~="bg-charcoal-950"][class*="rounded"]:not([class*="fixed"]) {
  background-color: #0f1011;
  background-image: var(--cn-pores), var(--cn-fine-faint);
  background-size: 380px 380px, 300px 300px;
  border-color: rgba(0, 0, 0, 0.65);
  box-shadow:
    inset 0 5px 14px rgba(0, 0, 0, 0.85),
    inset 0 -1px 0 rgba(255, 255, 255, 0.06),
    0 1px 0 rgba(255, 255, 255, 0.13);
}

/* Text cut into the concrete: shadow at the top edge, light catching the bottom lip. */
body.theme-concrete :is(h1, h2, h3, h4):not(.text-gold-gradient):not(.text-3d-white) {
  text-shadow: 0 -1px 1px rgba(0, 0, 0, 0.85), 0 1px 0 rgba(255, 255, 255, 0.16);
}
body.theme-concrete :is(p.uppercase, span.uppercase, label) {
  text-shadow: 0 1px 0 rgba(0, 0, 0, 0.6);
}

/* Inputs are holes in the slab. */
body.theme-concrete :is(input[type="text"], input[type="email"], input[type="tel"], input[type="search"], textarea, select) {
  background-color: #0b0c0d;
  background-image: var(--cn-fine-faint);
  border-color: rgba(0, 0, 0, 0.7);
  box-shadow:
    inset 0 8px 18px rgba(0, 0, 0, 0.95),
    inset 0 -1px 0 rgba(255, 255, 255, 0.07),
    0 1px 0 rgba(255, 255, 255, 0.14);
}
body.theme-concrete :is(input, textarea, select):focus {
  box-shadow:
    inset 0 8px 18px rgba(0, 0, 0, 0.95),
    0 0 0 2px rgba(232, 205, 138, 0.55);
}

/* Primary buttons sit on top of the concrete: raised, pressable. */
body.theme-concrete :is(a, button)[class*="from-gold-300"][class*="to-gold-700"],
body.theme-concrete :is(a, button)[class~="bg-gold-300"]:not([aria-pressed]) {
  background-image: linear-gradient(180deg, #f3e2ad 0%, #d3ad57 52%, #a17c34 100%);
  box-shadow:
    0 5px 0 #66501f,
    0 10px 16px -2px rgba(0, 0, 0, 0.65),
    inset 0 1px 0 rgba(255, 255, 255, 0.7),
    inset 0 -2px 0 rgba(0, 0, 0, 0.16);
  translate: 0 -2px;
  transition: translate 0.12s ease, box-shadow 0.12s ease;
}
body.theme-concrete :is(a, button)[class*="from-gold-300"][class*="to-gold-700"]:hover,
body.theme-concrete :is(a, button)[class~="bg-gold-300"]:not([aria-pressed]):hover {
  translate: 0 -3px;
}
body.theme-concrete :is(a, button)[class*="from-gold-300"][class*="to-gold-700"]:active,
body.theme-concrete :is(a, button)[class~="bg-gold-300"]:not([aria-pressed]):active {
  translate: 0 2px;
  box-shadow:
    0 1px 0 #66501f,
    0 3px 6px rgba(0, 0, 0, 0.6),
    inset 0 1px 0 rgba(255, 255, 255, 0.5);
}

/* Photos pressed into the slab: an inner lip all the way round, catch-light on the bottom edge. */
body.theme-concrete .deboss {
  position: relative;
  box-shadow: 0 1px 0 rgba(255, 255, 255, 0.17), 0 -1px 0 rgba(0, 0, 0, 0.8);
}
body.theme-concrete .deboss::after {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: inherit;
  pointer-events: none;
  z-index: 2;
  box-shadow:
    inset 0 7px 16px rgba(0, 0, 0, 0.8),
    inset 0 0 0 3px rgba(0, 0, 0, 0.45),
    inset 0 -2px 0 rgba(255, 255, 255, 0.13);
}

/* The rotating wheel: a round recess with the lettering running around its lip. */
body.theme-concrete .badge-wheel::before {
  content: "";
  position: absolute;
  inset: -5px;
  border-radius: 50%;
  background-color: #0d0e0f;
  background-image: var(--cn-fine-faint), radial-gradient(circle at 50% 30%, #1d1e20, #0a0a0b 70%);
  box-shadow:
    inset 0 7px 14px rgba(0, 0, 0, 0.95),
    inset 0 -2px 3px rgba(255, 255, 255, 0.12),
    0 1px 0 rgba(255, 255, 255, 0.2),
    0 -1px 0 rgba(0, 0, 0, 0.85);
}
`;
fs.writeFileSync("src/app/concrete.css", css);
console.log("concrete.css", (css.length / 1024).toFixed(1) + " KB");
